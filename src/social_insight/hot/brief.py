"""热点话题标题 → 精准简要（确定性压缩）。

━━━ 定位 ━━━

这是**帮助创作**的 MCP，不是打分工具。给 AI 的每一条热点要包含
「标题 + 一段简要」，其中简要的作用是**解释补充话题本身**——
让 AI 知道「这是什么事」，而不是再猜一遍标题在问什么。

━━━ 为什么不用 AI 生成摘要 ━━━

1. **服务器不内置生成式 AI** —— 调用方就是 LLM，再调一次是重复付费 + 黑盒化
2. 用户明确要求：**规则全部写死可查，绝不添加原文没有的信息**
3. 实测结论（2026-10-13）：9 个热源里**没有源提供可用原生摘要**
   （掘金 `brief` 字段存在但全为空；其余源只有 title）

━━━ 压缩规则（逐条可查）━━━

按固定顺序执行，每条规则都是**纯剥离**，不做改写：

R1 剥疑问外壳 —— 去掉「如何看待…」「怎么评价…」「？」，保留事实部分
R2 剥引导语 —— 「刚刚！」「突发！」「太可怕了」这类情绪引导
R3 剥装饰引号 —— 「」“” 去掉，内容不动
R4 剥冗余后缀 —— 「网友：」「评论区」等来源尾巴
R5 剥重复感叹 —— 连续「！！！」归一
R6 保底不改 —— 剥离比例 > 50% 视为「标题本身是问句」，**原文返回**

保险丝：R6 是核心安全机制。宁可少压缩，不可失真。
"""

from __future__ import annotations

import re

# ── R1 疑问外壳 ──────────────────────────────────────────────────

#: 「如何看待…？」「怎么评价…」这类**从句**（通常出现在中后部）。
#: 要求以标点或句首开头，避免吃掉正常标题里的字。
_ASK_CLAUSE = re.compile(
    r"[，,；;。．]\s*"
    r"(?:如何|怎么|怎样|为何|为什么)"
    r"[^？?。！\n]{0,40}"
    r"[？?]"
    r"\s*$"
)

#: 标题**主体本身就是问句**（开头即提问，如「为什么会这样？」）。
#: 这类标题压缩价值低，且剥离比例高，交给保险丝处理——
#: 这里只负责**去掉结尾问号**，不动内容。
_ASK_ONLY = re.compile(r"[？?]\s*$")

#: 结尾的疑问短语（不带问号的悬挂，如「…意味着什么」）
_ASK_TAIL_PHRASE = re.compile(
    r"[，,；;。]\s*(?:意味着|说明了|反映了|背后)[^，,。！？\n]{0,20}\s*$"
)

# ── R2 情绪引导语 ────────────────────────────────────────────────
#: ⚠️ 必须连同后面的**标点**一起吃掉——
#: 实测踩过：写成 `[...][！!，,。\s]*` 时「突发：」只剥掉「突发」，
#: 留下孤零零的「：」开头（「：某地发生地震」）。
_HYPE_PREFIX = re.compile(
    r"^\s*(?:刚刚|最新|突发|震惊|太可怕|离谱|逆天|炸裂|狂飙|重磅|"
    r"定了|官宣)"
    r"[！!，,。：:、\s]*"
)

# ── R3 装饰引号 ──────────────────────────────────────────────────
_DECOR_QUOTES = re.compile(r"[「」“”『』《》]")

# ── R4 来源尾巴 ──────────────────────────────────────────────────
_SRC_TAIL = re.compile(r"\s*(?:网友|评论区|博主|UP主|作者)[:：].*$")

# ── R5 重复感叹 ──────────────────────────────────────────────────
_MULTI_BANG = re.compile(r"([！!])\1{1,}")

#: 压缩比上限：剥离超过这个比例就放弃（标题本身可能是问句）
_MAX_STRIP_RATIO = 0.5


def compress_title(word: str) -> tuple[str, bool]:
    """把热点标题压成精准简要。

    返回 ``(简要, 是否压缩过)``。

    ⚠️ **绝不添加原文没有的信息** —— 所有规则都是删除/归一化，
       不做同义替换、不补全、不改写。原文没有的词不会出现。

    保险丝：若剥离比例超过 50%，判定「标题本身就是问句」，
    返回原文。宁可少压缩，不可失真。
    """
    if not word:
        return "", False

    original = word.strip()
    if not original:
        return "", False

    s = original
    before_len = len(s)

    # ⚠️ 注意顺序：从句（有标点引导）优先，避免误吃正常标题
    # R1a 疑问从句（「，如何看待…？」整段）
    s = _ASK_CLAUSE.sub("", s)
    # R1b 疑问短语尾巴（「，意味着什么」）
    s = _ASK_TAIL_PHRASE.sub("", s)
    # R1c 仅去结尾问号（主体是问句时不动内容，交给保险丝）
    s = _ASK_ONLY.sub("", s)

    # R2 情绪引导前缀（连标点一起剥）
    s = _HYPE_PREFIX.sub("", s)

    # R4 来源尾巴
    s = _SRC_TAIL.sub("", s)

    # R3 装饰引号
    s = _DECOR_QUOTES.sub("", s)

    # R5 重复感叹归一
    s = _MULTI_BANG.sub(r"\1", s)

    # 收尾清理：多余空白、悬挂标点
    s = re.sub(r"[，,；;\s]+$", "", s)
    s = re.sub(r"^[，,；;\s]+", "", s)
    s = re.sub(r"\s{2,}", " ", s).strip()

    # 保险丝 1：剥空了 → 返回原文
    if not s:
        return original, False

    # 保险丝 2：剥离过多 → 标题本身是问句，原文返回
    stripped_ratio = 1 - len(s) / before_len if before_len else 0.0
    if stripped_ratio > _MAX_STRIP_RATIO:
        return original, False

    # 保险丝 3：压缩后过短（<4 字）信息不足 → 原文返回
    if len(s) < 4:
        return original, False

    # 保险丝 4：压缩**没有任何实质变化** → 视为未压缩（宁实勿虚）。
    #
    # ⚠️ 判据必须是「字符串是否真变短」，而不是「核心内容是否改变」。
    #    实测踩过两个相反方向的错：
    #      ① 用「去掉问号」作判据 →「红星照耀中国：新…」标了 true 但内容没动
    #         （虚假标记，调用方误以为做过精简）
    #      ② 用「核心内容是否改变」作判据 →「刚刚！A股上涨」剥掉情绪前缀
    #         被误判为无增量（核心"A股上涨"没变），有效规则形同虚设
    #
    #    正解：**剥掉任何东西都算压缩**（哪怕只是情绪前缀或装饰引号），
    #    因为对 AI 读题确实有减负。只有「一个字都没变」才算未压缩。
    if s == original:
        return original, False

    # 保险丝 5：**只剥了问号**（内容一字未动）→ 视为未压缩。
    #
    # 例：「为什么会这样？」→「为什么会这样」。
    # 去掉问号对 AI 理解毫无帮助，标成"压缩过"是虚报。
    # （与保险丝 4 的分工：4 管"完全没动"，5 管"只动了问号"）
    if s == original.replace("？", "").replace("?", ""):
        return original, False

    return s, True


def brief_length_ok(brief: str, *, maximum: int = 120) -> bool:
    """简要长度约束（防止异常长标题撑爆上下文）。"""
    return 0 < len(brief) <= maximum


__all__ = ["compress_title", "brief_length_ok"]
